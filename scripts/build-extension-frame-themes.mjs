#!/usr/bin/env node
// Write src/shared/extension-frame-themes.generated.ts: the value of every
// THEME_TOKENS custom property in every built-in theme, so the Studio server
// can draw an extension's frame in a browser's theme on its first paint.
//
//   node scripts/build-extension-frame-themes.mjs          # write it
//   node scripts/build-extension-frame-themes.mjs --check  # fail when it is stale
//
// Read from the app's stylesheet (src/renderer/src/assets/index.css: a bare
// `:root` block, then one `:root[data-theme="<id>"]` block per theme) and the
// design system's tokens (design-system/foundations/tokens.css: `:root` for
// light, `[data-mode="dark"]` for dark), with every `var()` resolved. Which
// themes are light comes from the boot script's list (public/boot-theme.js).

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = 'src/shared/extension-frame-themes.generated.ts'

/** Top-level rules: `{ selectors, declarations }`, @-rules skipped. */
function rulesOf(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//gu, '')
  const rules = []
  let depth = 0
  let start = 0
  let selector = ''
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index]
    if (char === '{') {
      if (depth === 0) {
        selector = text.slice(start, index).trim()
        start = index + 1
      }
      depth += 1
    } else if (char === '}') {
      depth -= 1
      if (depth === 0) {
        if (!selector.startsWith('@'))
          rules.push({ selectors: selector.split(',').map((s) => s.trim()), body: text.slice(start, index) })
        start = index + 1
      }
    } else if (char === ';' && depth === 0) {
      start = index + 1
    }
  }
  return rules.map(({ selectors, body }) => {
    const declarations = {}
    for (const match of body.matchAll(/(--[\w-]+)\s*:\s*([^;{}]+);/gu))
      declarations[match[1]] = match[2].trim().replace(/\s+/gu, ' ')
    return { selectors, declarations }
  })
}

function collect(rules, selector) {
  const declarations = {}
  for (const rule of rules) if (rule.selectors.includes(selector)) Object.assign(declarations, rule.declarations)
  return declarations
}

function resolve(value, lookup, depth = 0) {
  if (depth > 24) return value
  return value.replace(/var\(\s*(--[\w-]+)\s*(?:,\s*([^()]*(?:\([^()]*\))?[^()]*))?\)/gu, (_, name, fallback) => {
    const found = lookup(name)
    if (found !== undefined) return resolve(found, lookup, depth + 1)
    return fallback !== undefined ? resolve(fallback.trim(), lookup, depth + 1) : ''
  })
}

export function buildFrameThemes(repo = REPO) {
  const app = rulesOf(readFileSync(join(repo, 'src/renderer/src/assets/index.css'), 'utf8'))
  const system = rulesOf(readFileSync(join(repo, 'design-system/foundations/tokens.css'), 'utf8'))
  const sdk = readFileSync(join(repo, 'packages/extension-sdk/src/index.ts'), 'utf8')
  const list = /export const THEME_TOKENS = \[([\s\S]*?)\] as const/u.exec(sdk)?.[1] ?? ''
  const tokens = [...list.matchAll(/'(--[\w-]+)'/gu)].map((match) => match[1])
  const themes = readFileSync(join(repo, 'src/shared/app-theme.ts'), 'utf8')
  const ids = [...new Set([...themes.matchAll(/^\s+id: '([\w-]+)',/gmu)].map((match) => match[1]))].filter(
    (id) => id !== 'system',
  )
  // The light-surfaced themes, as the boot script lists them (a test holds it to LIGHT_SURFACE_THEMES).
  const boot = readFileSync(join(repo, 'src/renderer/public/boot-theme.js'), 'utf8')
  const lightList = /var LIGHT_SURFACES = \{([\s\S]*?)\}/u.exec(boot)?.[1] ?? ''
  const lightIds = new Set([...lightList.matchAll(/['"]?([\w-]+)['"]?\s*:/gu)].map((match) => match[1]))
  const base = collect(app, ':root')
  const light = collect(system, ':root')
  const dark = collect(system, '[data-mode="dark"]')
  const out = {}
  for (const id of ids) {
    const theme = collect(app, `:root[data-theme="${id}"]`)
    const mode = lightIds.has(id) ? 'light' : 'dark'
    const lookup = (name) => theme[name] ?? base[name] ?? (mode === 'dark' ? dark[name] : undefined) ?? light[name]
    const values = {}
    for (const token of tokens) {
      const raw = lookup(token)
      if (raw !== undefined) values[token] = resolve(raw, lookup)
    }
    out[id] = { colorScheme: mode, tokens: values }
  }
  return out
}

export function renderFrameThemes(themes) {
  return `// GENERATED by scripts/build-extension-frame-themes.mjs — do not edit by hand.
// The value of every THEME_TOKENS custom property in each built-in theme, read
// from src/renderer/src/assets/index.css and design-system/foundations/tokens.css,
// for the Studio server to draw an extension's frame in a browser's theme.

import type { ExtensionFrameTheme } from './extension-frames'

export const EXTENSION_FRAME_THEMES: Readonly<Record<string, ExtensionFrameTheme>> = ${JSON.stringify(themes, null, 2)}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = renderFrameThemes(buildFrameThemes())
  const path = join(REPO, OUTPUT)
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== text) {
      console.error(`${OUTPUT} is stale: run node scripts/build-extension-frame-themes.mjs`)
      process.exit(1)
    }
  } else {
    writeFileSync(path, text)
    console.log(`wrote ${OUTPUT}`)
  }
}

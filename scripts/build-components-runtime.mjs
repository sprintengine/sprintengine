#!/usr/bin/env node
// Write src/server/extensions/frames/components-runtime.generated.ts: the
// components panel module (`@sprintengine/extension-sdk/components`, from
// packages/extension-sdk/src/components/) bundled into one ES module, as a
// string the Studio server puts into every components panel's frame document.
// A panel's imports of the module and of its JSX runtime both load it.
//
//   node scripts/build-components-runtime.mjs          # write it
//   node scripts/build-components-runtime.mjs --check  # fail when it is stale

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { buildSync } from 'esbuild'

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..')
export const OUTPUT = 'src/server/extensions/frames/components-runtime.generated.ts'
const ENTRY = 'packages/extension-sdk/src/components/index.ts'

export function bundleComponentsRuntime() {
  const result = buildSync({
    entryPoints: [join(REPO, ENTRY)],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    write: false,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  })
  return result.outputFiles[0].text
}

export function renderComponentsRuntime(code) {
  return `// GENERATED by scripts/build-components-runtime.mjs from ${ENTRY} — do not edit by hand.

/** The components panel module, one ES module, as the hidden guest loads it. */
export const COMPONENTS_RUNTIME_SOURCE = ${JSON.stringify(code)}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rendered = renderComponentsRuntime(bundleComponentsRuntime())
  const path = join(REPO, OUTPUT)
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(path, 'utf8')
    } catch {}
    if (current !== rendered) {
      console.error(`${OUTPUT} is stale: run node scripts/build-components-runtime.mjs`)
      process.exit(1)
    }
  } else writeFileSync(path, rendered)
}
